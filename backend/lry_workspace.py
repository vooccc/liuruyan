"""`.lry/` 项目工作区加载器

读取当前工作区的 `.lry/rules/` / `.lry/PROJECT_NOTES.md` 等文件，
拼装成可注入 system prompt 的文本。

设计文档：`_docs/lry_workspace_design.md`

## 加载入口

- `resolve_workspace_root()` → 解析当前 task 的工作区根目录
- `load_project_rules(root)` → `.lry/rules/*.md` 按字典序拼接
- `load_project_notes(root)` → `.lry/PROJECT_NOTES.md` 全文（带截断）

## 工作区解析优先级

1. ContextVar `_current_working_directory_var`（subagent / 显式注入）
2. `paths.legacy_project_root()`（柳如烟自身项目根，用于自 dogfood）

返回 None 表示无法解析，调用方应降级为不注入。

## 并发安全

所有函数无状态、纯读取。多 task 并发时各自从 ContextVar 拿不同的 root，
互不干扰。**严禁**在本模块加任何全局可变状态。

## prompt cache 影响

`load_project_rules` 输出会被注入到 system prompt 的 static 段（caller
即 `agent.get_system_prompt` 负责）。因此：

- 文件按字典序拼接 → 同一项目稳定，不会因目录列出顺序漂移击穿缓存
- 单文件读取失败时跳过该文件，**剩余文件仍按字典序输出**（不重排）
- 超出软上限时截断而不是丢弃，截断点稳定（前 N 字符）
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional


# === 目录 / 文件命名常量 ===

LRY_DIR_NAME = ".lry"
RULES_SUBDIR = "rules"
WORKFLOWS_SUBDIR = "workflows"
MEMORY_SUBDIR = "memory"
PRIVATE_SUBDIR = "private"  # .lry/private/ 下的内容不入 git（见 ensure_lry_gitignore）
ARCHIVE_SUBDIR = "archive"  # Phase 10：归档被 `archive_lry_file` 工具移走的内容
NOTES_FILE = "PROJECT_NOTES.md"
CODE_MAP_FILE = "CODE_MAP.md"
GITIGNORE_FILE = ".gitignore"
INDEX_FILE = "INDEX.md"  # Phase 8：自动维护的"本项目记住了什么"汇总，由 regenerate_index_file 生成

# INDEX.md 幂等 marker：首行检查这串以判断该文件是否由本模块自动生成。
# 用户手写的 INDEX.md 不含 marker 时**不会被覆盖**（人机契约——工具不抢用户笔）。
# v1 标识后续改格式可以 bump，让老文件识别并可选迁移。
_INDEX_MARKER = "<!-- LRY_AUTO_INDEX_MARKER_v1 - do not edit; regenerated by backend.lry_workspace.regenerate_index_file -->"

# `.lry/.gitignore` 模板。private/ 和 archive/ 强制不入 git；其他条目给用户参考（第
# 一次被 ensure_lry_gitignore 创建时写上，用户后续想加条目自己改）。
# marker 行用于幂等判断：已含这行就不再重写，避免覆盖用户的自定义。
_GITIGNORE_MARKER = "# 柳如烟 .lry/ workspace（auto-generated by ensure_lry_gitignore）"
_GITIGNORE_DEFAULT_BODY = f"""\
{_GITIGNORE_MARKER}
# private/ 下的所有内容**永远**不入 git：存敏感记忆 / API key / 用户机密。
private/
# archive/ 下是 archive_lry_file 工具移走的旧内容，默认不入 git（噪音大、历史在 git log 里已经够用）。
archive/

# 可选：如果把 memory/ 视为运行期沉淀（不 review），解开注释忽略。
# memory/
"""

# 容量软上限（字符数；token 概算 ≈ chars × 0.5 中英混合）
# 见 _docs/lry_workspace_design.md §9.2
RULES_MAX_CHARS = 12000   # ≈ 3K token
NOTES_MAX_CHARS = 8000    # ≈ 2K token


# === 工作区根解析 ===

def resolve_workspace_root() -> Optional[Path]:
    """解析当前调用上下文的工作区根目录。

    优先级：
    1. ContextVar `backend.tools.builtin.file_tools._current_working_directory_var`
       —— subagent 启动 / 显式注入会 set 这个 ContextVar
    2. 当前 session 绑定的工作区目录（如果有 session 活跃上下文）
    3. `paths.legacy_project_root()` —— 柳如烟自身项目根，用于自 dogfood

    任何异常或路径不存在 → 返回 None。caller 应据此降级为不注入。
    """
    try:
        from .tools.builtin.file_tools import _current_working_directory_var

        raw = _current_working_directory_var.get()
        if raw:
            p = Path(raw).expanduser().resolve()
            if p.exists() and p.is_dir():
                return p
    except Exception:
        pass

    try:
        from .llm_client import _current_session_id_var
        sid = _current_session_id_var.get()
        if sid:
            from .session import get_session_manager
            mgr = get_session_manager()
            sess = mgr.get_session_sync(sid)
            if sess:
                ws = sess.get_pinned_workspace_directory()
                if ws:
                    p = Path(ws).expanduser().resolve()
                    if p.exists() and p.is_dir():
                        return p
    except Exception:
        pass

    try:
        from . import paths

        p = paths.legacy_project_root().resolve()
        if p.exists() and p.is_dir():
            return p
    except Exception:
        pass

    return None


# === 内部工具 ===

def _read_text_safe(path: Path) -> Optional[str]:
    """读文本，失败返 None。utf-8-sig 兼容 BOM。"""
    try:
        return path.read_text(encoding="utf-8-sig")
    except OSError:
        return None
    except UnicodeDecodeError:
        # 兜底再试 utf-8 / gbk（极少见，Windows 老编辑器留下的）
        for enc in ("utf-8", "gbk"):
            try:
                return path.read_text(encoding=enc)
            except (OSError, UnicodeDecodeError):
                continue
        return None


def _truncate_with_marker(text: str, limit: int, source_label: str) -> str:
    """超出 limit 字符时截断，并在末尾追加 warning marker。"""
    if len(text) <= limit:
        return text
    return text[:limit] + (
        f"\n\n<!-- WARNING: {source_label} exceeded {limit} chars, truncated. "
        f"Consider archiving older entries to .lry/memory/. -->"
    )


# === 项目 rules 加载 ===

def load_project_rules(workspace_root: Path) -> str:
    """加载 `.lry/rules/*.md` 拼接文本。

    - 不存在或无 .md 文件 → 返回空串
    - 按文件名字典序（locale-independent）拼接，保证顺序稳定（缓存友好）
    - 单文件读失败 / 内容空白 → 跳过该文件
    - 总长度超 RULES_MAX_CHARS → 截断 + warning marker
    - 输出前缀含 `## 本项目特有约束` 标题，便于模型识别

    返回的文本可以直接拼接到 system prompt static 段末尾。
    """
    if workspace_root is None:
        return ""

    rules_dir = workspace_root / LRY_DIR_NAME / RULES_SUBDIR
    if not rules_dir.is_dir():
        return ""

    parts: list[str] = []
    # 字典序排序：按文件名 ASCII 排序而非 locale-aware，避免不同环境差异
    for path in sorted(rules_dir.glob("*.md"), key=lambda p: p.name):
        if not path.is_file():
            continue
        content = _read_text_safe(path)
        if not content:
            continue
        content = content.strip()
        if not content:
            continue
        parts.append(f"<!-- .lry/rules/{path.name} -->\n{content}")

    if not parts:
        return ""

    body = "\n\n".join(parts)
    body = _truncate_with_marker(body, RULES_MAX_CHARS, ".lry/rules/")

    return (
        "## 本项目特有约束（.lry/rules/）\n\n"
        "以下规则由本项目积累而成，**永远在线**。违反这些规则可能导致项目层面 bug。\n\n"
        f"{body}"
    )


# === workflow 索引加载（仅 description，不含步骤） ===

# frontmatter `description: ...` 解析正则。tolerate 引号 / 多余空格
_WF_DESC_RE_LINE = "description:"

def _extract_workflow_description(text: str) -> Optional[str]:
    """从 workflow 文件 frontmatter 抽 description 字段。

    简化解析：只看头 30 行里以 `description:` 开头的第一行。
    没有就返 None。设计上不强制每个 workflow 有 description——
    没有就只展示文件名。
    """
    for line in text.splitlines()[:30]:
        stripped = line.strip()
        if stripped.lower().startswith(_WF_DESC_RE_LINE):
            value = stripped[len(_WF_DESC_RE_LINE):].strip()
            # 去掉两端引号
            if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
                value = value[1:-1]
            return value or None
    return None


def load_codemap_pointer(workspace_root: Path) -> str:
    """如果 `.lry/CODE_MAP.md` 存在，返回一句话提示注入 system prompt。

    不全文注入——CODE_MAP 通常很长，不应每轮都吃 token。
    只告诉 agent 它存在 + 用 `read_file('.lry/CODE_MAP.md')` 取。
    """
    if workspace_root is None:
        return ""

    target = workspace_root / LRY_DIR_NAME / CODE_MAP_FILE
    if not target.is_file():
        return ""
    try:
        size = target.stat().st_size
    except OSError:
        return ""

    # 抽 H1 标题做更友好的提示（前 5 行扫描）
    title = ""
    try:
        with target.open("r", encoding="utf-8-sig") as fh:
            for _ in range(5):
                line = fh.readline()
                if not line:
                    break
                stripped = line.strip()
                if stripped.startswith("# "):
                    title = stripped[2:].strip()
                    break
    except OSError:
        pass

    title_part = f"《{title}》" if title else ""
    return (
        f"## 本项目代码地图（.lry/{CODE_MAP_FILE}）\n\n"
        f"本项目有一份代码地图{title_part}（{size} 字节）。"
        f"需要了解项目结构 / 模块职责 / 黄金路径时，"
        f"用 `read_file('.lry/{CODE_MAP_FILE}')` 读取。"
    )


def load_workflow_index(workspace_root: Path) -> str:
    """加载 `.lry/workflows/*.md` 的索引（仅 name + description）。

    与 rules 不同：workflows 不全文注入，只列名字 + 一句话描述。
    agent 想执行某个 workflow → 调 `get_project_workflow(name)` 工具拿完整步骤。

    这样可以注册一堆 workflow 而不爆 prompt，按需召唤。
    """
    if workspace_root is None:
        return ""

    wf_dir = workspace_root / LRY_DIR_NAME / WORKFLOWS_SUBDIR
    if not wf_dir.is_dir():
        return ""

    entries: list[tuple[str, Optional[str]]] = []
    for path in sorted(wf_dir.glob("*.md"), key=lambda p: p.name):
        if not path.is_file():
            continue
        text = _read_text_safe(path)
        if not text:
            continue
        name = path.stem  # .md 之前的部分
        desc = _extract_workflow_description(text)
        entries.append((name, desc))

    if not entries:
        return ""

    body_lines = []
    for name, desc in entries:
        if desc:
            body_lines.append(f"- **{name}**: {desc}")
        else:
            body_lines.append(f"- **{name}**")

    return (
        "## 本项目可用工作流（.lry/workflows/）\n\n"
        "用 `get_project_workflow(name='<name>')` 取完整步骤再执行。\n\n"
        + "\n".join(body_lines)
    )


# === 项目 notes 加载 ===

def load_project_notes(workspace_root: Path) -> str:
    """加载 `.lry/PROJECT_NOTES.md` 全文。

    - 文件不存在 → 返回空串
    - 内容超出 NOTES_MAX_CHARS → 截断 + warning marker（保留前段）
    - 输出前缀含 `## 本项目当前进度` 标题
    """
    if workspace_root is None:
        return ""

    notes_path = workspace_root / LRY_DIR_NAME / NOTES_FILE
    if not notes_path.is_file():
        return ""

    content = _read_text_safe(notes_path)
    if not content:
        return ""

    content = content.strip()
    if not content:
        return ""

    content = _truncate_with_marker(content, NOTES_MAX_CHARS, ".lry/PROJECT_NOTES.md")

    return (
        "## 本项目当前进度（.lry/PROJECT_NOTES.md）\n\n"
        f"{content}"
    )


def lry_private_memory_dir(workspace_root: Path) -> Path:
    """返回 `.lry/private/memory/` 绝对路径。不保证存在。

    调用方负责 mkdir。目录存在与否跟是否"启用私密"无关——
    任何 `save_project_memory(private=True)` 调用都会 mkdir+write。
    """
    return workspace_root / LRY_DIR_NAME / PRIVATE_SUBDIR / MEMORY_SUBDIR


def lry_archive_dir(workspace_root: Path, kind: str, *, private: bool = False) -> Path:
    """Phase 10：返回某种 `kind` 归档目录的绝对路径（不保证存在）。

    布局约定（保留原子目录结构，方便将来 restore）：
      `.lry/archive/rules/`          rule 归档
      `.lry/archive/workflows/`      workflow 归档
      `.lry/archive/memory/`         公开 memory 归档
      `.lry/archive/private/memory/` 私密 memory 归档

    `archive/` 整体被 `.gitignore` 的 `archive/` 行忽略（由 `ensure_lry_gitignore`
    Phase 10 扩展保证），因此归档内容默认也不入 git。

    `kind` 必须是 {rule, workflow, memory} 之一；别的值抛 ValueError。
    """
    kind = (kind or "").strip().lower()
    archive_root = workspace_root / LRY_DIR_NAME / ARCHIVE_SUBDIR
    if kind == "rule":
        return archive_root / RULES_SUBDIR
    if kind == "workflow":
        return archive_root / WORKFLOWS_SUBDIR
    if kind == "memory":
        if private:
            return archive_root / PRIVATE_SUBDIR / MEMORY_SUBDIR
        return archive_root / MEMORY_SUBDIR
    raise ValueError(f"unsupported archive kind: {kind!r}; expected rule|workflow|memory")


def ensure_lry_gitignore(workspace_root: Path) -> Optional[Path]:
    """保证 `.lry/.gitignore` 存在且至少含 `private/` 规则。

    幂等：
    - 文件不存在 → 写入默认模板
    - 文件存在且含 `_GITIGNORE_MARKER` 行 → 不动（认为是同一管理方式创建的）
    - 文件存在但不含 marker → 追加默认模板到末尾（保留用户既有内容）

    返回 gitignore 绝对路径；无法解析 workspace_root 或写失败 → None。

    **静默降级**：任何异常吞掉不抛——审计/gitignore 不能阻断主流程。
    """
    if workspace_root is None:
        return None
    try:
        lry_dir = workspace_root / LRY_DIR_NAME
        lry_dir.mkdir(parents=True, exist_ok=True)
        gi_path = lry_dir / GITIGNORE_FILE

        if gi_path.is_file():
            existing = _read_text_safe(gi_path) or ""
            if _GITIGNORE_MARKER in existing:
                return gi_path
            # 不改用户已有内容，只在末尾追加默认块
            new_content = existing.rstrip() + "\n\n" + _GITIGNORE_DEFAULT_BODY
            gi_path.write_text(new_content, encoding="utf-8")
            return gi_path

        gi_path.write_text(_GITIGNORE_DEFAULT_BODY, encoding="utf-8")
        return gi_path
    except OSError:
        return None


# === INDEX.md 自动维护（Phase 8） ===


def _index_parse_frontmatter_value(text: str, key: str) -> Optional[str]:
    """从 markdown 文件头部 frontmatter 里抽 `key: value` 的 value。

    tolerate 引号 + 大小写；找不到返 None。只扫前 15 行 frontmatter 块。
    """
    if not text.startswith("---"):
        return None
    for line in text.splitlines()[1:16]:
        if line.strip() == "---":
            break
        if ":" not in line:
            continue
        k, _, v = line.partition(":")
        if k.strip().lower() == key.lower():
            v = v.strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in ("'", '"'):
                v = v[1:-1]
            return v or None
    return None


def _index_collect_rules(lry_dir: Path) -> list[dict]:
    """收集 rules 元数据。按 severity 降序、slug 字典序排列。"""
    rules_dir = lry_dir / RULES_SUBDIR
    if not rules_dir.is_dir():
        return []
    order = {"critical": 0, "warning": 1, "info": 2}
    out = []
    for path in rules_dir.glob("*.md"):
        if not path.is_file():
            continue
        text = _read_text_safe(path) or ""
        out.append(
            {
                "slug": path.stem,
                "severity": (_index_parse_frontmatter_value(text, "severity") or "unknown"),
                "topic": _index_parse_frontmatter_value(text, "topic") or path.stem,
                "added": _index_parse_frontmatter_value(text, "added") or "",
            }
        )
    out.sort(key=lambda r: (order.get(r["severity"], 9), r["slug"]))
    return out


def _index_collect_workflows(lry_dir: Path) -> list[dict]:
    """收集 workflows 元数据。按文件名字典序排。"""
    wf_dir = lry_dir / WORKFLOWS_SUBDIR
    if not wf_dir.is_dir():
        return []
    out = []
    for path in sorted(wf_dir.glob("*.md"), key=lambda p: p.name):
        if not path.is_file():
            continue
        text = _read_text_safe(path) or ""
        out.append(
            {
                "name": path.stem,
                "description": _index_parse_frontmatter_value(text, "description") or "",
            }
        )
    return out


def _index_collect_memory(lry_dir: Path) -> tuple[list[dict], int]:
    """收集公开 memory + private count。

    返回：(public items, private_count)。private 条目**不**进 items 列表——
    INDEX.md 公开文本里绝不该泄漏私密主题。private_count 只做聚合数字。
    """
    public_items: list[dict] = []
    mem_dir = lry_dir / MEMORY_SUBDIR
    if mem_dir.is_dir():
        for path in sorted(
            mem_dir.glob("*.md"), key=lambda p: p.name, reverse=True
        ):
            if not path.is_file():
                continue
            text = _read_text_safe(path) or ""
            public_items.append(
                {
                    "filename": path.name,
                    "kind": _index_parse_frontmatter_value(text, "kind") or "",
                    "topic": _index_parse_frontmatter_value(text, "topic") or path.stem,
                    "added": _index_parse_frontmatter_value(text, "added") or "",
                    "by": _index_parse_frontmatter_value(text, "by") or "",
                }
            )

    priv_count = 0
    priv_dir = lry_dir / PRIVATE_SUBDIR / MEMORY_SUBDIR
    if priv_dir.is_dir():
        priv_count = sum(1 for _ in priv_dir.glob("*.md"))
    return public_items, priv_count


def _index_render(lry_dir: Path) -> str:
    """生成 INDEX.md 内容字符串。包含 marker 首行。"""
    from datetime import datetime, timezone

    rules = _index_collect_rules(lry_dir)
    workflows = _index_collect_workflows(lry_dir)
    memories, priv_count = _index_collect_memory(lry_dir)

    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    parts: list[str] = [
        _INDEX_MARKER,
        "",
        "# 本项目记住了什么",
        "",
        f"_由柳如烟自动维护 · 最后更新 {ts}_",
        "",
        "> 本文件是柳如烟在本项目积累的内容索引。规则 / 工作流 / 记忆由工具写入时自动更新；",
        "> **手写的 `INDEX.md`（没有 marker）不会被覆盖**——想接管请删掉 marker 即可。",
        "",
    ]

    parts.extend([f"## 规则（{len(rules)}）", ""])
    if rules:
        parts.append("按 severity 降序、slug 字典序排列。")
        parts.append("")
        parts.append("| Severity | Slug | Topic | Added |")
        parts.append("|---|---|---|---|")
        for r in rules:
            parts.append(
                f"| {r['severity']} | `{r['slug']}` | {r['topic']} | {r['added'] or '—'} |"
            )
    else:
        parts.append("_暂无规则。_")
    parts.append("")

    parts.extend([f"## 工作流（{len(workflows)}）", ""])
    if workflows:
        for w in workflows:
            desc = w["description"] or "—"
            parts.append(f"- **{w['name']}** — {desc}")
    else:
        parts.append("_暂无工作流。_")
    parts.append("")

    parts.extend(
        [
            f"## 记忆（public: {len(memories)} · private: {priv_count}）",
            "",
            "按文件名倒序（≈ 时间倒序）。**私密条目只统计数量、不显示主题**。",
            "",
        ]
    )
    if memories:
        parts.append("| Kind | Topic | Added | By |")
        parts.append("|---|---|---|---|")
        for m in memories:
            parts.append(
                f"| {m['kind'] or '—'} | {m['topic']} | {m['added'] or '—'} | {m['by'] or '—'} |"
            )
    else:
        parts.append("_暂无公开记忆。_")
    parts.append("")

    parts.extend(["## 关键文件", ""])
    parts.append(
        f"- {'✅' if (lry_dir / NOTES_FILE).is_file() else '⏳'} `PROJECT_NOTES.md`"
    )
    parts.append(
        f"- {'✅' if (lry_dir / CODE_MAP_FILE).is_file() else '⏳'} `CODE_MAP.md`"
    )
    parts.append(
        f"- {'✅' if (lry_dir / 'README.md').is_file() else '⏳'} `README.md`（人类手写，不入自动索引）"
    )
    parts.append(
        f"- {'✅' if (lry_dir / GITIGNORE_FILE).is_file() else '⏳'} `.gitignore`（首次写 private 时自动）"
    )
    parts.append("")

    return "\n".join(parts)


def regenerate_index_file(workspace_root: Path) -> Optional[Path]:
    """重新生成 `.lry/INDEX.md`。

    幂等行为：
    - `.lry/` 不存在 → 不生成（没工作区）
    - `INDEX.md` 已存在且**不含 marker** → 认为是用户手写，**不动**
    - `INDEX.md` 存在且含 marker → 覆盖重写
    - `INDEX.md` 不存在 → 新建

    返回写入路径；失败 / 跳过返 None。**静默降级**：任何异常吞掉，不阻断主流程。
    """
    if workspace_root is None:
        return None
    try:
        lry_dir = workspace_root / LRY_DIR_NAME
        if not lry_dir.is_dir():
            return None

        target = lry_dir / INDEX_FILE
        if target.is_file():
            existing = _read_text_safe(target) or ""
            if _INDEX_MARKER not in existing.split("\n", 1)[0]:
                # 用户手写的，不动
                return None

        content = _index_render(lry_dir)
        target.write_text(content, encoding="utf-8")
        return target
    except OSError:
        return None


